import { jsPDF } from 'jspdf';
import { StorePersona, Review, ActionItem, SentimentAlert, DashboardMetrics } from '../types';

export function generateWeeklyExecutiveReport(
  persona: StorePersona,
  reviews: Review[],
  actions: ActionItem[],
  alerts: SentimentAlert[],
  metrics: DashboardMetrics
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  let y = 20;

  // Header Banner
  doc.setFillColor(15, 23, 42); // Deep Slate (#0F172A)
  doc.roundedRect(15, y, pageWidth - 30, 32, 4, 4, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text('CLUEY CART | Executive Feedback Intelligence Report', 22, y + 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(165, 180, 252); // Soft indigo
  doc.text(`Store: ${persona.name} | Category: ${persona.category} | Generated: ${new Date().toLocaleDateString()}`, 22, y + 22);

  y += 42;

  // Executive Summary Metrics Section
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text('1. Executive Feedback Telemetry', 15, y);
  y += 8;

  const colWidth = (pageWidth - 30 - 9) / 4;
  const metricsData = [
    { label: 'Net Sentiment', val: `${metrics.netSentimentScore > 0 ? '+' : ''}${metrics.netSentimentScore}%` },
    { label: 'Reviews Ingested', val: `${metrics.totalReviews}` },
    { label: 'Noise Filtered', val: `${metrics.noisePercentage}% (${metrics.noiseReviewsCount})` },
    { label: 'Key Suggestions', val: `${actions.length}` },
  ];

  metricsData.forEach((m, idx) => {
    const x = 15 + idx * (colWidth + 3);
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(x, y, colWidth, 18, 2, 2, 'FD');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(m.label, x + 4, y + 6);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(15, 23, 42);
    doc.text(m.val, x + 4, y + 14);
  });

  y += 26;

  // Active Anomaly Alerts
  if (alerts.length > 0) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(225, 29, 72); // Rose/Crimson
    doc.text('2. Smart Sentiment Trend Alerts (Anomalies)', 15, y);
    y += 8;

    alerts.forEach((alert) => {
      doc.setFillColor(255, 241, 242);
      doc.setDrawColor(254, 205, 211);
      doc.roundedRect(15, y, pageWidth - 30, 16, 2, 2, 'FD');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(225, 29, 72);
      doc.text(`[${alert.severity.toUpperCase()}] ${alert.attribute} (+${alert.percentage_surge}%)`, 20, y + 6);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(71, 85, 105);
      doc.text(doc.splitTextToSize(alert.message, pageWidth - 45), 20, y + 11);

      y += 20;
    });
    y += 4;
  }

  // Recommended Product & Operational Suggestions
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.text('3. Key Improvement Suggestions', 15, y);
  y += 8;

  actions.slice(0, 5).forEach((action, i) => {
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(15, y, pageWidth - 30, 20, 2, 2, 'FD');

    // Priority pill
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    const isCrit = action.priority === 'critical';
    doc.setTextColor(isCrit ? 225 : 79, isCrit ? 29 : 70, isCrit ? 72 : 229);
    doc.text(`[${action.priority.toUpperCase()}] • ${action.category}`, 20, y + 6);

    // Title
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    const titleText = action.title;
    doc.text(doc.splitTextToSize(titleText, pageWidth - 45), 20, y + 11);

    // Impact
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(`Impact: ${action.estimated_impact}`, 20, y + 16);

    y += 24;
  });

  // Footer
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(
    'Generated by CLUEY CART • Powered by Google Gemini AI & Supabase • Autonomous E-Commerce Operational Engine',
    15,
    285
  );

  // Trigger browser download
  const cleanStoreName = persona.name.toLowerCase().replace(/[^a-z0-9]/g, '_');
  doc.save(`cluey_cart_${cleanStoreName}_weekly_report.pdf`);
}
